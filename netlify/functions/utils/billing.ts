/**
 * Shared billing helpers for recurring (monthly) payment plans.
 * Used by api-org (syncPaymentPlans on enrollment) and the monthly-billing cron
 * so the period key and due date are computed identically on both sides.
 */
import { orgDayKey } from '../../../src/lib/payment-plans';

/** Billing period key for a date, e.g. "2026-07". Used to dedupe monthly invoices. */
export function billingPeriodKey(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
}

/**
 * Детерминированный id помесячного начисления.
 *
 * Ключ идемпотентности вместо случайного id: «студент × курс × месяц» — это
 * ровно то, что должно существовать в единственном экземпляре. Дедуп до сих пор
 * делался чтением перед записью, а между чтением и записью помещается второй
 * запрос: два менеджера, нажавшие «Начислить за месяц» одновременно (или крон
 * вместе с менеджером), выставляли студенту два одинаковых счёта, и оба видели
 * успех. Собрать это обратно потом можно только руками.
 *
 * С этим id вторую запись отвергает сама база — независимо от того, кто и
 * откуда пишет.
 *
 * У начислений, созданных ДО этого изменения, id случайный, поэтому чтение
 * перед записью остаётся: оно закрывает легаси, а детерминированный id —
 * гонку.
 */
export function monthlyPlanId(orgId: string, courseId: string, studentId: string, period: string): string {
  // Разделитель '__': id организации/курса/студента — это Firestore-идентификаторы
  // без слэшей, но одиночное '_' в них встречается.
  return `mp__${orgId}__${courseId}__${studentId}__${period}`;
}

/** Конец дня `dueDay` указанного месяца, с клампом к длине месяца (февраль, 31 → 28/29). */
function endOfDueDay(year: number, month: number, dueDay: number): Date {
  const lastDay = new Date(year, month + 1, 0).getDate();
  const day = Math.min(Math.max(1, dueDay), lastDay);
  return new Date(year, month, day, 23, 59, 59);
}

/**
 * Deadline (ISO) for a monthly invoice: the `dueDay` of the period's month,
 * end of day. Clamped to the last day of the month for short months.
 *
 * ── Счёт не может родиться уже просроченным ──
 * Раньше срок считался строго от месяца периода, без оглядки на то, КОГДА счёт
 * выставляют. Поэтому любое начисление после 10-го числа появлялось с уже
 * истёкшим сроком:
 *   • студента завели в группу 25 августа (api-org.ts, автоматическая ветка) —
 *     счёт со сроком «10.08» создавался вообще без участия менеджера;
 *   • менеджер нажал «Начислить за месяц» 15-го — то же самое.
 * Дальше просрочка работала по-настоящему: студенту сразу уходило «Оплатить до
 * 10.08.2026» (дата в прошлом), а через несколько дней — «Оплата просрочена».
 * Продлить срок из интерфейса нечем: EditPlanAmountModal правит только сумму.
 *
 * Поэтому, если день срока в месяце периода уже прошёл по календарю
 * организации, срок переносится на ТОТ ЖЕ день следующего месяца. Ритм оплаты
 * сохраняется («всегда 10-е»), и это можно объяснить родителю одной фразой —
 * в отличие от «дата выставления плюс сколько-то дней», которая давала бы
 * произвольные числа вроде 22-го.
 *
 * `now` параметризован ради тестируемости; по умолчанию — текущий момент.
 */
export function billingDeadlineISO(d: Date, dueDay = 10, now: Date = new Date()): string {
  const year = d.getFullYear();
  const month = d.getMonth();

  // Сдвигаем, ПОКА срок не окажется в будущем, а не ровно на один месяц.
  //
  // Однократный сдвиг закрывал только начисление за текущий месяц. Но месяц в
  // «Оплатах за месяц» переключается стрелками, и кнопка «Начислить за месяц»
  // ими не ограничена: менеджер 3 августа возвращается на июнь, чтобы добить
  // пропущенного студента, — кандидат 10.06 сдвигался на 10.07 и всё равно
  // оставался в прошлом. Счёт снова рождался просроченным, студенту немедленно
  // уходило «Оплатить до 10.07», и debt-reminders сразу считал его должником.
  //
  // Сравниваем календарные ДНИ в зоне организации (UTC+6): функция выполняется
  // на Netlify в UTC, и сравнение моментов сдвигало бы границу суток на шесть
  // часов — ровно та ошибка, из-за которой существует orgDayKey.
  const today = orgDayKey(now);
  // Верхняя граница нужна только как страховка от бесконечного цикла на
  // мусорной дате: 120 месяцев заведомо перекрывают любой реальный разрыв.
  for (let shift = 0; shift < 120; shift++) {
    const candidate = endOfDueDay(year, month + shift, dueDay);
    if (candidate.toISOString().slice(0, 10) >= today) return candidate.toISOString();
  }
  return endOfDueDay(year, month + 120, dueDay).toISOString();
}

/**
 * Ошибка Firestore «документ уже существует» (gRPC ALREADY_EXISTS = 6).
 *
 * Нужна там, где запись идёт через `create` ради идемпотентности: дубль — это
 * штатный исход гонки, а вот таймаут или отказ в правах означают, что счёт НЕ
 * выставлен. Ловить их одним `catch {}` значило выдавать потерянные начисления
 * за успешный прогон — крон помесячный, и вернуться к пропущенному месяцу уже
 * нечем.
 */
export function isAlreadyExists(err: unknown): boolean {
  const e = err as any;
  return e?.code === 6 || e?.code === 'already-exists' || /already exists/i.test(String(e?.message || ''));
}
