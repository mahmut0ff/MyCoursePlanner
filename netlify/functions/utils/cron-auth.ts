/**
 * Доступ к запланированным (cron) функциям.
 *
 * ── Зачем ──
 * Netlify запускает такие функции по расписанию, но их HTTP-адрес остаётся
 * публичным: `/.netlify/functions/monthly-billing` отвечает любому, кто пришлёт
 * POST. Ни одна из этих функций не проверяла вызывающего вообще — то есть
 * посторонний мог запустить месячное начисление, ночную рассылку требований
 * оплаты или открытие зарплатных ведомостей когда угодно и сколько угодно раз.
 * Данные при этом не подделываются (функции считают по своим правилам), но
 * побочные эффекты настоящие: студентам уходят уведомления, у организаций
 * появляются документы, а идемпотентность защищает от дублей, не от самого
 * факта запуска.
 *
 * ── Разрешаем три пути ──
 *  1. Запуск самой платформой по расписанию — Netlify помечает такой вызов
 *     заголовком `x-nf-event: schedule`.
 *  2. Явный секрет `x-cron-secret`, совпадающий с переменной окружения
 *     CRON_SECRET. Это путь для ручного прогона и для внешнего планировщика.
 *  3. Аутентифицированный суперадмин — чтобы прогнать вручную из админки.
 *
 * ── Почему отказ включается явно, через CRON_ENFORCE ──
 * Цена ошибки здесь несимметрична. Лишний прогон рассылки — неприятность.
 * ЛОЖНЫЙ отказ — это не выставленные за месяц счета, неоткрытые зарплатные
 * ведомости и молчащие напоминания, причём молча: крон запускается раз в месяц,
 * никто не смотрит на его ответ, и обнаружится это в лучшем случае через
 * несколько недель по жалобам.
 *
 * Признак планового запуска (`x-nf-event: schedule`) приходит по HTTP, то есть
 * он и не граница доверия, и не гарантия: подделать его можно, а вот что
 * платформа его действительно шлёт — утверждение о поведении Netlify, которое
 * в этом репозитории проверить нечем. Поэтому по умолчанию функция ведёт себя
 * как раньше и только пишет предупреждение в лог, а отказ включается
 * переменной CRON_ENFORCE=true — после того, как в конкретном окружении
 * убедились, что плановые прогоны проходят.
 *
 * Порядок развёртывания: задать CRON_SECRET → дождаться планового прогона →
 * убедиться по логам, что он опознан → выставить CRON_ENFORCE=true.
 */
import type { HandlerEvent } from '@netlify/functions';
import { verifyAuth, isSuperAdmin, jsonResponse } from './auth';

const lower = (headers: Record<string, any> | undefined | null): Record<string, string> => {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers || {})) out[k.toLowerCase()] = String(v ?? '');
  return out;
};

/**
 * Возвращает 403-ответ, если вызывающему нельзя запускать эту функцию, и null,
 * если можно.
 */
export async function cronAccessError(event: HandlerEvent) {
  const headers = lower(event.headers as any);

  // 1. Плановый запуск самой Netlify.
  if (headers['x-nf-event'] === 'schedule') return null;

  // 2. Общий секрет. Сравниваем по длине и содержимому явно: пустой секрет в
  //    окружении не должен превращаться в «подходит любой пустой заголовок».
  const secret = process.env.CRON_SECRET || '';
  if (secret && headers['x-cron-secret'] === secret) return null;

  // 3. Суперадмин — ручной прогон.
  const user = await verifyAuth(event).catch(() => null);
  if (user && isSuperAdmin(user)) return null;

  // Опознать вызывающего не удалось.
  if (String(process.env.CRON_ENFORCE || '').toLowerCase() !== 'true') {
    console.warn(
      '[cron-auth] Неопознанный запуск запланированной функции пропущен: CRON_ENFORCE не включён. '
      + 'Задайте CRON_SECRET и CRON_ENFORCE=true, чтобы закрыть публичный запуск.',
    );
    return null;
  }

  return jsonResponse(403, {
    error: 'Эта функция запускается по расписанию. Для ручного запуска нужен заголовок x-cron-secret или вход суперадмином.',
    code: 'cron_forbidden',
  });
}
