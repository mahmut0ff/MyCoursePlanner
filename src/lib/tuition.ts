/**
 * Договорная цена обучения — «сколько ИМЕННО ЭТОТ студент платит за ИМЕННО ЭТОТ
 * курс». Общее определение для SPA и Netlify-функций.
 *
 * ── Зачем сущность, если цена есть у курса ──
 * `course.price` была единой на всех. Реальные академии так не работают: у брата
 * скидка, у льготника договорная цена, пришедший с середины года платит своё. До
 * сих пор это выражалось правкой суммы у КОНКРЕТНОГО месячного начисления, а на
 * следующий месяц сумма «переносилась» эвристикой — взять последнее начисление
 * пары студент+курс. Эвристика отказывает ровно там, где дороже всего: начислений
 * ещё нет (новичок), они списаны, или их выставил крон по цене курса — и студент
 * молча получал прайс вместо своей цены.
 *
 * Поэтому цена стала фактом, а не следом: одна запись на пару (студент × курс),
 * которую читают ВСЕ пути начисления. `course.price` осталась прайсом — значением
 * по умолчанию для тех, у кого своей цены нет, и базой, от которой считается
 * скидка (`listAmount` в начислении).
 *
 * Лежит в `src/lib`, а не в `netlify/functions/utils`, по той же причине, что и
 * payment-plans.ts: `tsconfig.app.json` покрывает только `src`, поэтому хелпер из
 * дерева функций недостижим для страницы — и две копии неизбежно разъезжаются.
 * Здесь только чистые правила; чтение из Firestore живёт в
 * netlify/functions/utils/tuition.ts.
 */

export const TUITION_COLLECTION = 'studentTuitions';

/**
 * «Курс не выбран поимённо» — поставить цену по всем курсам, где студент учится.
 * Литерал общий для окна и для ручки: разъехавшись, они молча перестали бы
 * понимать друг друга (ручка увидела бы курс с несуществующим id и записала
 * ставку в пустоту).
 */
export const TUITION_ALL_COURSES = '__all__';

/**
 * Детерминированный id ставки. Разделитель '__' — как в monthlyPlanId: id
 * организации/студента/курса это Firestore-идентификаторы без слэшей, но
 * одиночное '_' внутри них встречается.
 *
 * Пара (организация, студент, курс) существует в единственном экземпляре, и
 * читают её всегда по известным ключам. Детерминированный id даёт точечное
 * чтение (getAll, один round-trip на пачку), не требует ни одного составного
 * индекса — в этом проекте они не задеплоены — и делает повторную запись
 * идемпотентной сама собой.
 */
export function tuitionDocId(orgId: string, studentId: string, courseId: string): string {
  return `tu__${orgId}__${studentId}__${courseId}`;
}

/** Ключ пары для клиентских карт (Map<key, amount>) — организация там одна. */
export function tuitionKey(studentId: string, courseId: string): string {
  return `${studentId}|${courseId}`;
}

/**
 * Сумма из записи ставки, или null — «ставки нет».
 *
 * Ноль — ЗАДАННАЯ ставка, а не её отсутствие: так выражают стипендиата, который
 * не платит ничего. Отличать это от «ставки нет» обязательно, иначе стипендиату
 * каждый месяц выставлялась бы цена курса. Отрицательную сумму не принимаем ни
 * при чтении, ни при записи: счёт на минус — это не скидка, а испорченные данные.
 */
export function readTuitionAmount(doc: any): number | null {
  const n = Number(doc?.amount);
  return Number.isFinite(n) && n >= 0 ? n : null;
}

/**
 * Сумма начисления: ставка студента, а если её нет — цена курса.
 *
 * ЕДИНСТВЕННОЕ место, где записан этот приоритет, — ровно как planDebt для
 * долга. Оба пути автоматического начисления (зачисление в группу и месячный
 * крон), подстановка в «Начислить за месяц» и ручной счёт обязаны давать одно и
 * то же число: расхождение здесь означает, что студенту выставят разные суммы в
 * зависимости от того, кто нажал кнопку.
 *
 * Нечитаемая цена курса — это 0 («не задана»), а не NaN: NaN уехал бы в документ
 * начисления и сломал бы каждый последующий пересчёт долга.
 */
export function effectiveChargeAmount(rate: number | null | undefined, coursePrice: unknown): number {
  if (rate !== null && rate !== undefined && Number.isFinite(rate)) return Number(rate);
  const price = Number(coursePrice);
  return Number.isFinite(price) ? price : 0;
}

/** Карта ставок из ответа ручки: Map<'studentId|courseId', amount>. */
export function tuitionRateMap(rows: any[]): Map<string, number> {
  const map = new Map<string, number>();
  for (const r of rows || []) {
    const amount = readTuitionAmount(r);
    if (amount === null || !r?.studentId || !r?.courseId) continue;
    map.set(tuitionKey(String(r.studentId), String(r.courseId)), amount);
  }
  return map;
}
