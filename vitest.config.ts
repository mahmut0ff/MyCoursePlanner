import { defineConfig } from 'vitest/config';
import react from '@vitejs/plugin-react';
import path from 'path';

export default defineConfig({
  plugins: [react()],
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./src/setupTests.ts'],
    // Тесты идут в той же зоне, что и прод: Netlify-функции всегда выполняются
    // в UTC, а машины разработчиков стоят в зоне академии (UTC+6). Из-за этого
    // TZ-зависимый баг мог пройти локально насквозь — ровно так и случилось с
    // окном зарплатной ведомости: локально в Бишкеке границы месяца сходились,
    // а на Netlify июльская ведомость захватывала 30 июня и оплачивала его
    // второй раз. Пин делает такой промах воспроизводимым.
    env: { TZ: 'UTC' },
    // `.claude/worktrees` — рабочие копии репозитория, которые агентские сессии
    // создают внутри проекта. Без этого исключения vitest подхватывает КАЖДУЮ
    // копию: один и тот же тест выполняется по разу на worktree, прогон растёт
    // кратно их числу, а в отчёте появляются падения из чужого, давно
    // отставшего коммита — то есть верификация собственных правок перестаёт
    // что-либо значить. `dist` и `netlify/functions` в сборке тестов не нужны
    // по той же причине: там лежат артефакты, а не исходники.
    exclude: ['**/node_modules/**', '**/dist/**', '.claude/worktrees/**'],
    alias: {
      '@': path.resolve(__dirname, './src'),
    },
    coverage: {
      provider: 'v8',
      reporter: ['text', 'json', 'html'],
    },
  },
});
